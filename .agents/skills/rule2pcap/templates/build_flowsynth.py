#!/usr/bin/env python3
"""Write NAME.pcap: <what the traffic is>, which fires sid <SID>.

Rebuild (any venv with the skill's requirements.txt installed):
    <venv>/bin/python -I build.py

<Provenance. Say which parts come from public sources (with links) and
which are invented: hosts, ports, timing, headers, bodies.>

---- template notes (delete this block in a real build) ----
Flowsynth template, for application traffic over TCP or UDP. The demo makes
a DNS lookup, then an HTTP POST check-in and its reply, which fire the demo
rules in templates/demo.rules (sids 9000101 and 9000102).

Build the payload bytes in Python, write them as a .synth file, compile it
with Flowsynth, then post-process with scapy. The post-processing gives
random ISNs (Flowsynth uses 10 and 100), realistic timestamps (Flowsynth
stamps wall-clock time) and a FIN teardown (Flowsynth emits none). Copy
pcapkit.py next to this file.
-------------------------------------------------------------
"""

import datetime
import os
import random
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)  # python -I leaves the script's directory off sys.path
sys.dont_write_bytecode = True  # keep __pycache__ out of the output directory

import pcapkit as pk  # noqa: E402
from scapy.all import UDP, rdpcap, wrpcap  # noqa: E402

NAME = "demo-flowsynth"
SEED = 9000101  # the target sid: same seed, same bytes on every rebuild
START = datetime.datetime(2024, 3, 12, 14, 7, 31, 250000, tzinfo=datetime.timezone.utc)

# Victims in RFC1918 space, outside hosts in documentation ranges
# (192.0.2.0/24, 198.51.100.0/24, 203.0.113.0/24).
VICTIM, RESOLVER, SERVER = "10.20.30.41", "10.20.0.53", "203.0.113.80"
# Fixed unicast MACs on every flow. Never let Flowsynth pick: its random MACs
# change per packet and can have the group bit set.
VICTIM_MAC, RESOLVER_MAC, GW_MAC = (
    "f8:bc:12:4e:21:07",
    "00:25:90:1c:44:3a",
    "00:1b:54:c2:8e:01",
)
HOST = "updates.example.net"
WAN_HOSTS = {SERVER}  # replies from these cross the internet
RTT = (0.035, 0.060)  # internet round trip range, seconds
# Each TCP host's OS: its SYN options, windows and timestamps
# (pk.set_tcp_stack). Flowsynth's own are window 8192 and no options.
STACKS = {VICTIM: "windows", SERVER: "linux"}
# Segment size: when both ends use timestamps (Linux, macOS), each segment
# carries a 12-byte option, so data segments are 12 bytes smaller.
# both ends timestamping leave MSS - 12 for data (1460 IPv4, 1440 IPv6)
SEGMENT = (
    (1428 if ":" in VICTIM else 1448)
    if pk.both_timestamp(STACKS[VICTIM], STACKS[SERVER])
    else None
)

rng = random.Random(SEED)


def gap(p, new_flow, earlier):
    """Seconds between the previous packet and this one. Edit to taste.

    The capture point here is the victim's LAN, so WAN_HOSTS are remote. For
    an inbound attack on a local server, put the outside client in WAN_HOSTS
    instead. Add think time (e.g. a user clicking a link) by checking the
    payload of p.
    """
    if new_flow:
        return rng.uniform(0.05, 0.30)  # think time before a new connection
    if UDP in p and p[UDP].sport == 53:
        return rng.uniform(0.004, 0.020)  # resolver answer
    # an RTT for a remote reply; back-to-back segments of one flight are fast
    return pk.reply_gap(p, earlier, WAN_HOSTS, rng, rtt=RTT)


def build():
    body = b'{"id":"8f3a1c22","os":"Windows 10 Pro 19045","av":"none","v":"1.1"}'
    request = pk.http_message(
        "POST /api/v2/checkin HTTP/1.1",
        [
            ("Content-Type", "application/json"),
            ("User-Agent", "WinHTTP-Loader/1.1"),
            ("Host", HOST),
            ("Connection", "Keep-Alive"),
            ("Cache-Control", "no-cache"),
        ],
        body,
    )
    response = pk.http_message(
        "HTTP/1.1 200 OK",
        [
            ("Date", pk.http_date(START)),  # never later than the packet's own time
            ("Server", "nginx"),
            ("Content-Type", "application/json"),
            ("Connection", "keep-alive"),
        ],
        b'{"status":"ok","sleep":300}',
    )
    query, answer = pk.dns_messages(rng.randrange(1, 0xFFFF), HOST, SERVER)
    # ephemeral ports for the client's OS: pk.WINDOWS_PORTS or pk.LINUX_PORTS
    dns_port, http_port = (rng.randrange(*pk.WINDOWS_PORTS) for _ in range(2))

    synth, pcap = (
        os.path.join(here, f"{NAME}.synth"),
        os.path.join(here, f"{NAME}.pcap"),
    )
    with open(synth, "w") as f:
        f.write("# Generated by build.py -- edit that, not this.\n")
        f.write(
            pk.flow_line(
                "d", "udp", VICTIM, dns_port, RESOLVER, 53, VICTIM_MAC, RESOLVER_MAC
            )
        )
        f.write(pk.event_line("d", ">", query) + pk.event_line("d", "<", answer))
        f.write(
            pk.flow_line(
                "h", "tcp", VICTIM, http_port, SERVER, 80, VICTIM_MAC, GW_MAC, SEGMENT
            )
        )
        f.write(pk.event_line("h", ">", request) + pk.event_line("h", "<", response))
    pk.compile_synth(synth, pcap)

    pkts = pk.randomize_isns(list(rdpcap(pcap)), rng)
    pk.restamp(pkts, START, gap)
    # idle: how long before the closer sends its FIN (see pk.teardown)
    pkts = pk.teardown(
        pkts, closer="client", idle=0.2, remote=WAN_HOSTS, rtt=RTT, rng=rng
    )
    pkts = pk.set_tcp_stack(pkts, STACKS, rng)
    # TTLs as seen at the capture point (local Windows 128, remote a few hops
    # down) and per-host IP IDs; Flowsynth stamps TTL 64 and ID 1 everywhere.
    pkts = pk.set_ip_fields(pkts, rng, ttl={VICTIM: 128, RESOLVER: 64, SERVER: 52})
    wrpcap(pcap, pkts)
    os.chmod(pcap, 0o644)
    return pcap


if __name__ == "__main__":
    print(build())
